function diaDoAnoHome(data){
  const d = data || new Date();
  const inicio = new Date(d.getFullYear(), 0, 0);
  return Math.floor((new Date(d.getFullYear(), d.getMonth(), d.getDate()) - inicio) / 86400000);
}

// Duas frases por dia. "rotacao" sobe a cada toque; além disso muda a cada 6 h do dia.
function frasesDoDia(data, rotacao){
  const d = data || new Date();
  const dia = ((diaDoAnoHome(d) - 1) % 365 + 365) % 365; // dia 366 volta à frase do dia 1
  const A = FRASES_730[(dia * 2) % FRASES_730.length];
  const B = FRASES_730[(dia * 2 + 1) % FRASES_730.length];
  const alternar = (dia + Math.floor(d.getHours() / 6) + (rotacao || 0)) % 2;
  return alternar === 0 ? { frase: A, outra: B } : { frase: B, outra: A };
}

function dicaDoDia(data, textoFraseExibida){
  const d = data || new Date();
  let i = (diaDoAnoHome(d) * 7) % DICAS_ORIZON.length;
  if (DICAS_ORIZON[i] === textoFraseExibida) i = (i + 1) % DICAS_ORIZON.length;
  return DICAS_ORIZON[i];
}
